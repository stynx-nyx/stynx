// Pure finite source generation: no workspace imports, database access or runtime query assembly.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const check = process.argv.includes('--check');
if (process.argv.slice(2).some((argument) => argument !== '--check')) {
  throw new Error('Usage: node packages/worklist/scripts/generate-queue-update-queries.mjs [--check]');
}
const banner = '// Generated by scripts/generate-queue-update-queries.mjs. Edit that source, then regenerate.\n';
const projection = "\n  id,\n  tenant_id as \"tenantId\",\n  code,\n  name,\n  description,\n  strategy,\n  strategy_config as \"strategyConfig\",\n  required_permission as \"requiredPermission\",\n  supervisor_permission as \"supervisorPermission\",\n  claim_limit as \"claimLimit\",\n  default_sla_seconds as \"defaultSlaSeconds\",\n  default_sla_business_days as \"defaultSlaBusinessDays\",\n  default_calendar_key as \"defaultCalendarKey\",\n  meta,\n  created_by as \"createdBy\",\n  updated_by as \"updatedBy\",\n  created_at as \"createdAt\",\n  updated_at as \"updatedAt\"\n";
// The parser always supplies strategy. The other eight fields determine the mask.
// Keep column/bind order, including the three deadline columns sharing one bit.
/** @type {[bit: number, column: string, schema: string, cast: string][]} */
const fields = [
  [1, 'name', 'text', ''],
  [2, 'description', 'nullableText', ''],
  [0, 'strategy', 'text', ''],
  [4, 'strategy_config', 'serializedJson', '::jsonb'],
  [8, 'required_permission', 'text', ''],
  [16, 'supervisor_permission', 'text', ''],
  [32, 'claim_limit', 'nullableNumber', ''],
  [64, 'meta', 'serializedJson', '::jsonb'],
  [128, 'default_sla_seconds', 'nullableNumber', ''],
  [128, 'default_sla_business_days', 'nullableNumber', ''],
  [128, 'default_calendar_key', 'nullableText', ''],
];
const header = banner + `import { defineQuery, sql } from '@stynx-nyx/data';
import { z } from 'zod';
import { queueUpdateRow, type QueueUpdateQuery } from '../queue-update-schemas.js';
const text = z.string();
const nullableText = text.nullable();
const nullableNumber = z.number().nullable();
// JSON.stringify may return undefined through a supplied toJSON method.
const serializedJson = text.optional();
`;
/** @type {Map<string, string>} */
const outputs = new Map();
for (let chunk = 0; chunk < 2; chunk += 1) {
  const parts = [header];
  for (let mask = chunk * 128; mask < (chunk + 1) * 128; mask += 1) {
    const parameters = ['text'];
    const assignments = [];
    for (const [bit, column, schema, cast] of fields) {
      if (bit !== 0 && (mask & bit) === 0) continue;
      parameters.push(schema);
      assignments.push(`${column} = $${parameters.length}${cast}`);
    }
    assignments.push('updated_at = clock_timestamp()', "updated_by = current_setting('app.actor_id')::uuid");
    const statement = `update worklist.queues set ${assignments.join(', ')} where id = $1 returning ${projection}`;
    if (statement.includes('`') || statement.includes('${')) throw new Error('Non-literal queue update SQL');
    parts.push(`const query${mask} = defineQuery({
  name: 'worklist.queue.update.mask.${mask}',
  text: sql\`${statement}\`,
  params: z.tuple([${parameters.join(', ')}]),
  row: queueUpdateRow,
  expects: 'many',
});
`);
  }
  parts.push('export const selectQuery = (mask: number): QueueUpdateQuery => {\n  switch (mask) {\n');
  for (let mask = chunk * 128; mask < (chunk + 1) * 128; mask += 1) {
    parts.push(`    case ${mask}: return query${mask};`);
  }
  parts.push("    default: throw new TypeError('Missing fixed Worklist queue update definition');\n  }\n};\n");
  outputs.set(`../src/generated/queue-update-${String(chunk).padStart(2, '0')}.repository.ts`, parts.join('\n'));
}
outputs.set('../src/queue-update.repository.ts', banner + `import type { QueueUpdateQuery } from './queue-update-schemas.js';
import { selectQuery as chunk0 } from './generated/queue-update-00.repository.js';
import { selectQuery as chunk1 } from './generated/queue-update-01.repository.js';
export const selectQueueUpdateQuery = (mask: number): QueueUpdateQuery => {
  if (mask < 128) return chunk0(mask);
  if (mask < 256) return chunk1(mask);
  throw new TypeError('Missing fixed Worklist queue update definition');
};
`);
for (const [relative, source] of outputs) {
  const target = new URL(relative, import.meta.url);
  if (check) {
    if (readFileSync(target, 'utf8') !== source) throw new Error(`Generated queue update source is stale: ${relative}`);
  } else {
    mkdirSync(new URL('.', target), { recursive: true });
    writeFileSync(target, source);
  }
}
process.stdout.write(`${check ? 'Checked' : 'Generated'} 256 queue update definitions in ${outputs.size} files.\n`);
