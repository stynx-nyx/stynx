import { Global, Module, type DynamicModule } from '@nestjs/common';
import {
  PermissionCache,
  PermissionCacheMetrics,
  PermissionGuard,
  PermissionQueryService,
  resolveAuthOptions,
  STYNX_AUTH_OPTIONS,
  STYNX_PERMISSION_CACHE_BACKEND,
  StynxAuthGuard,
  StynxJwtValidator,
} from '@stynx-nyx/auth';
import {
  InMemorySessionStore,
  resolveSessionsOptions,
  SessionJwtSigningService,
  SessionMirrorWriter,
  SessionService,
  STYNX_SESSIONS_OPTIONS,
  STYNX_SESSION_MIRROR,
  STYNX_SESSION_STORE,
  type StynxSessionSigningKeySet,
} from '@stynx-nyx/sessions';

// Keys are generated by each fixture. Sessions use the supported in-memory
// adapter and the real database mirror, signing, validation and permission path.
@Global()
@Module({})
export class FlowRuntimeAuthModule {
  static forRoot(keySet: StynxSessionSigningKeySet): DynamicModule {
    const issuer = 'https://stynx.testing.local';
    return {
      module: FlowRuntimeAuthModule,
      providers: [
        { provide: STYNX_AUTH_OPTIONS, useValue: resolveAuthOptions({ stynx: { issuer } }) },
        { provide: STYNX_PERMISSION_CACHE_BACKEND, useValue: null },
        {
          provide: STYNX_SESSIONS_OPTIONS,
          useValue: resolveSessionsOptions({
            issuer,
            redis: { url: 'redis://unused.test:6379' },
            jwt: { keySet },
          }),
        },
        { provide: STYNX_SESSION_STORE, useValue: new InMemorySessionStore() },
        { provide: STYNX_SESSION_MIRROR, useClass: SessionMirrorWriter },
        SessionJwtSigningService,
        SessionService,
        StynxJwtValidator,
        PermissionCacheMetrics,
        PermissionQueryService,
        PermissionCache,
        StynxAuthGuard,
        PermissionGuard,
      ],
      exports: [
        SessionJwtSigningService,
        SessionService,
        StynxJwtValidator,
        PermissionCacheMetrics,
        PermissionQueryService,
        PermissionCache,
        StynxAuthGuard,
        PermissionGuard,
      ],
    };
  }
}
