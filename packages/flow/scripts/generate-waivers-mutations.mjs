const schema = (table, column, operation) => {
  if (column === 'id' || column === 'tenant_id') return 'text';
  if (column === 'created_by' || column === 'updated_by') return 'actor';
  if (column === 'updated_at') return 'timestamp';
  if (['is_active', 'required', 'blocks_submit'].includes(column)) return 'optionalBoolean';
  if (['meta', 'validators', 'visible_if'].includes(column)) return 'optionalMetadata';
  if (column === 'options') return 'optionalArray';
  if (column === 'sort_order') return 'optionalInteger';
  if (table === 'forms' && column === 'version') return 'text';
  if (operation === 'update') return 'optionalText';
  if (['description', 'question_id', 'waived_by', 'expires_at'].includes(column)) return 'optionalText';
  return 'text';
};
