import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Closed public caller/parser census: four create shapes, 31 nonempty updates.
// Optional undefined fields are omitted by DesignTableStore. Nodes are separate.
const fields = ['code', 'label', 'adapter_key', 'adapter_config', 'meta'];
const createMasks = [7, 15, 23, 31];
const updateMasks = Array.from({ length: 31 }, (_, index) => index + 1);
const types = {
  id: 'text', tenant_id: 'text', code: 'text', label: 'text', adapter_key: 'text',
  adapter_config: 'metadata', meta: 'metadata', created_by: 'actor',
  updated_by: 'actor', updated_at: 'timestamp',
};
const output = resolve(dirname(fileURLToPath(import.meta.url)), '../src/internal/design/scope-mutations.repository.ts');
let source = `// Generated by scripts/generate-scope-queries.mjs; do not edit.
import { defineQuery, sql, type Transaction } from '@stynx-nyx/data';
import { z } from 'zod';

const text = z.unknown().pipe(z.string());
const actor = z.unknown().pipe(z.string().nullable());
const timestamp = z.unknown().pipe(z.instanceof(Date));
const metadata = z.unknown().pipe(z.custom<Record<string, unknown>>((value) => typeof value === 'object' && value !== null && !Array.isArray(value)));
const opaqueRow = z.object({});
function isScopeMutationRow(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

`;
for (const operation of ['create', 'update']) {
  const masks = operation === 'create' ? createMasks : updateMasks;
  const definitions = masks.map((mask) => {
    const columns = fields.filter((_field, index) => (mask & (1 << index)) !== 0);
    if (operation === 'create') {
      const params = ['tenant_id', ...columns, 'created_by', 'updated_by'];
      return { mask, params, sql: `insert into flow.scopes (${params.join(', ')}) values (${params.map((_param, index) => `$${index + 1}`).join(', ')}) returning *` };
    }
    const updates = [...columns, 'updated_by', 'updated_at'];
    return { mask, params: ['id', ...updates], sql: `update flow.scopes set ${updates.map((column, index) => `${column} = $${index + 2}`).join(', ')} where id = $1::uuid returning *` };
  });
  for (const definition of definitions) {
    source += `const ${operation}${definition.mask} = defineQuery({
  name: 'flow.design.scopes.${operation}.${definition.mask}',
  text: sql\`${definition.sql}\`,
  params: z.tuple([${definition.params.map((param) => types[param]).join(', ')}]),
  row: opaqueRow,
  expects: 'many',
});

`;
  }
  const title = operation[0].toUpperCase() + operation.slice(1);
  source += `export function executeScope${title}(trx: Transaction, mask: number, values: readonly unknown[]) {
  switch (mask) {
`;
  for (const definition of definitions) {
    source += `    case ${definition.mask}:
      return trx.runGuarded(${operation}${definition.mask}, [${definition.params.map((_param, index) => `values[${index}]`).join(', ')}], isScopeMutationRow);
`;
  }
  source += `    default:
      throw new RangeError('Unreachable scope ${operation} column mask');
  }
}

`;
}
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== source) throw new Error('Scope query definitions are stale');
  console.log('Scope query definitions match all 35 closed statement shapes');
} else {
  writeFileSync(output, source);
  console.log(`Wrote 35 scope query definitions to ${output}`);
}
