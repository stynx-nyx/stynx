const schema = (_table, column) => {
  if (['meta', 'params', 'applicability', 'conditions'].includes(column)) return 'metadata';
  if (['sort_order', 'priority'].includes(column)) return 'integer';
  if (column === 'created_by' || column === 'updated_by') return 'actor';
  if (column === 'updated_at') return 'timestamp';
  return 'text';
};
