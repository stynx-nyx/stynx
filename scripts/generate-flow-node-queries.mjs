import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

// Authoring-time only. Runtime code selects a literal definition by its mask;
// it never interpolates a table, column, assignment, or SQL fragment.
/** @type {[column: string, schema: string][]} */
const columns = [
  ['graph_id', 'uuid'],
  ['code', 'text'],
  ['name', 'text'],
  ['kind', 'text'],
  ['decision_policy', 'text'],
  ['quorum_ratio', 'numeric'],
  ['allowed_actions', 'textArray'],
  ['sla_seconds', 'integer'],
  ['entry_rule', 'text'],
  ['exit_rule', 'text'],
  ['sort_order', 'integer'],
  ['meta', 'json'],
];
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = resolve(root, 'packages/flow/src/internal/design/generated');
const check = process.argv.includes('--check');
const chunkSize = 128;
/** @type {Map<string, string>} */
const files = new Map();
let queryCount = 0;

for (const operation of ['insert', 'update']) {
  const chunks = [];
  for (let chunk = 0; chunk < 2 ** columns.length / chunkSize; chunk += 1) {
    const definitions = [];
    const cases = [];
    for (let mask = chunk * chunkSize; mask < (chunk + 1) * chunkSize; mask += 1) {
      if (operation === 'update' && mask === 0) continue;
      const selected = columns.filter((_entry, bit) => (mask & (1 << bit)) !== 0);
      const names = selected.map(([column]) => column);
      const schemas = selected.map(([, schema]) => `p.${schema}`);
      let text;
      let params;
      if (operation === 'insert') {
        const allNames = ['tenant_id', ...names, 'created_by', 'updated_by'];
        const placeholders = allNames.map((_name, index) => `$${index + 1}`);
        text = `insert into flow.nodes (${allNames.join(', ')}) values (${placeholders.join(', ')}) returning *`;
        params = ['p.uuid', ...schemas, 'p.actor', 'p.actor'];
      } else {
        const assignments = [...names, 'updated_by', 'updated_at']
          .map((name, index) => `${name} = $${index + 2}`);
        text = `update flow.nodes set ${assignments.join(', ')} where id = $1::uuid returning *`;
        params = ['p.uuid', ...schemas, 'p.actor', 'p.timestamp'];
      }
      definitions.push(`const query${mask} = defineQuery({\n    name: 'flow.nodes.${operation}.mask.${mask}',\n    text: sql\`${text}\`,\n    params: z.tuple([${params.join(', ')}]),\n    row: nodeMutationRow,\n    expects: 'many',\n  });`);
      cases.push(`    case ${mask}: return query${mask};`);
      queryCount += 1;
    }
    const stem = `nodes-${operation}-${String(chunk).padStart(2, '0')}.repository`;
    chunks.push(stem);
    files.set(`${stem}.ts`, `// Generated by scripts/generate-flow-node-queries.mjs; do not edit.\nimport { defineQuery, sql } from '@stynx-nyx/data';\nimport { z } from 'zod';\nimport { nodeMutationParams as p, nodeMutationRow, type NodeMutationQuery } from '../node-mutation-schemas.js';\n\n${definitions.join('\n\n')}\n\nexport const selectQuery = (mask: number): NodeMutationQuery => {\n  switch (mask) {\n${cases.join('\n')}\n    default: throw new Error('Missing fixed Flow node mutation definition');\n  }\n};\n`);
  }
  files.set(`nodes-${operation}.repository.ts`, `// Generated by scripts/generate-flow-node-queries.mjs; do not edit.\nimport type { NodeMutationQuery } from '../node-mutation-schemas.js';\n${chunks.map((stem, index) => `import { selectQuery as chunk${index} } from './${stem}.js';`).join('\n')}\n\nexport const selectNode${operation === 'insert' ? 'Insert' : 'Update'}Query = (mask: number): NodeMutationQuery => {\n${chunks.map((_stem, index) => `  if (mask < ${(index + 1) * chunkSize}) return chunk${index}(mask);`).join('\n')}\n  throw new Error('Missing fixed Flow node mutation definition');\n};\n`);
}

const formatting = await resolveConfig(resolve(root, 'package.json'));
if (!check) mkdirSync(output, { recursive: true });
for (const [name, source] of files) {
  const path = resolve(output, name);
  const formatted = await format(source, { ...formatting, filepath: path });
  files.set(name, formatted);
  if (check) {
    if (readFileSync(path, 'utf8') !== formatted) throw new Error(`Stale generated Flow queries: ${name}`);
  } else {
    writeFileSync(path, formatted);
  }
}
console.log(JSON.stringify({ files: files.size, queries: queryCount, bytes: [...files.values()].reduce((sum, source) => sum + Buffer.byteLength(source), 0), check }));
