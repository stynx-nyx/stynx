#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, renameSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { format } from 'prettier';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'law/schemas/offline-import.schema.json'), 'utf8');
const schema = JSON.parse(source);
function validateClosedObjects(node) {
  if (node === null || typeof node !== 'object') return;
  if (
    node.type === 'object' &&
    node.additionalProperties !== false &&
    (node.additionalProperties === null || typeof node.additionalProperties !== 'object')
  )
    throw new Error('Import object rules require false or a schema for additionalProperties');
  Object.values(node).forEach(validateClosedObjects);
}
validateClosedObjects(schema);
const names = Object.fromEntries(
  Object.keys(schema.$defs).map((key) => [
    key,
    `OfflineImport${key[0].toUpperCase()}${key.slice(1)}`,
  ]),
);
function type(node) {
  if (Array.isArray(node.type))
    return node.type.map((value) => type({ ...node, type: value })).join(' | ');
  if (node.$ref) return names[node.$ref.split('/').at(-1)];
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (node.oneOf || node.anyOf)
    return (node.oneOf ?? node.anyOf).map((item) => `(${type(item)})`).join(' | ');
  if (node.type === 'array') return `readonly (${type(node.items)})[]`;
  if (node.type === 'object') {
    if (!node.properties) return `{ readonly [key: string]: ${type(node.additionalProperties)} }`;
    return `{ ${Object.entries(node.properties)
      .map(
        ([key, value]) =>
          `readonly ${JSON.stringify(key)}${node.required?.includes(key) ? '' : '?'}: ${type(value)};`,
      )
      .join('\n')} }`;
  }
  return node.type === 'integer' ? 'number' : node.type;
}
const body = await format(
  `// Generated by scripts/offline-import-schema-generate.mjs; do not edit.\n// Authority SHA-256: ${createHash('sha256').update(source).digest('hex')}\nexport const OFFLINE_IMPORT_SCHEMA = ${JSON.stringify(schema)} as const;\n${Object.entries(
    schema.$defs,
  )
    .map(([key, node]) => `export type ${names[key]} = ${type(node)};`)
    .join('\n')}\nexport type OfflineImportManifest = ${type(schema)};\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
const target = resolve(root, 'packages/offline-sync/src/import-schema.generated.ts');
const args = process.argv.slice(2);
if (args.length !== 1 || !['--check', '--write'].includes(args[0]))
  throw new Error('Use exactly --check or --write');
if (args[0] === '--check') {
  if (readFileSync(target, 'utf8') !== body)
    throw new Error('Offline import schema generation drift');
} else {
  const temporary = `${target}.${process.pid}.tmp`;
  writeFileSync(temporary, body);
  renameSync(temporary, target);
}
