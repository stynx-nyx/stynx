#!/usr/bin/env node
// Offline generation only: no consumer database connection and no policy repair.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitStatements } from '../tools/migration-linter/src/sql.ts';
import { format } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const files = [
  '0001_offline_sync.sql',
  '0002_durable_sync.sql',
  '0003_reservation_idempotency.sql',
  '0004_pending_state_and_conflict_actions.sql',
  '0005_initial_queue_status.sql',
  '0006_nullable_active_reservations.sql',
  '0007_range_administration.sql',
  '0008_import_receipts.sql',
  '0009_numbering_reconciliations.sql',
];
const objects = [];
const bindings = [];
const sources = [];
const migrationDir = resolve(root, 'packages/offline-sync/migrations');
for (const file of readdirSync(migrationDir).filter((name) => name.endsWith('.sql'))) {
  if (
    !files.includes(file) &&
    /\boffline\./u.test(readFileSync(resolve(migrationDir, file), 'utf8'))
  ) {
    throw new Error(`Unregistered offline migration: ${file}`);
  }
}
for (const file of files) {
  const text = readFileSync(resolve(root, 'packages/offline-sync/migrations', file), 'utf8');
  sources.push({
    path: `packages/offline-sync/migrations/${file}`,
    sha256: createHash('sha256').update(text).digest('hex'),
  });
  for (const statement of splitStatements(text)) {
    const sql = statement.text.replace(/^(?:\s*--[^\n]*(?:\n|$))+/u, '').trim();
    if (sql.length === 0) continue;
    if (
      /^(?:GRANT|REVOKE|ALTER DEFAULT PRIVILEGES|CREATE POLICY|DROP POLICY|ALTER (?:TABLE|FUNCTION|SCHEMA)[\s\S]*? OWNER TO)/u.test(
        sql,
      )
    ) {
      // Historical PUBLIC policies become explicitly bound application/reader policies.
      bindings.push(
        /^CREATE POLICY /u.test(sql) && !/\bTO\b/u.test(sql)
          ? sql.replace(/\bUSING\b/u, 'TO stynx_app, stynx_reader USING')
          : sql,
      );
    } else {
      if (
        !/^(?:CREATE (?:OR REPLACE )?(?:SCHEMA|TABLE|(?:UNIQUE )?INDEX|FUNCTION|TRIGGER)|ALTER TABLE|INSERT INTO|DO\s*\$|SET LOCAL|LOCK TABLE)/u.test(
          sql,
        )
      )
        throw new Error(`Unsupported offline statement in ${file}`);
      objects.push(sql);
    }
  }
}
// The artifact is applied once to fresh storage. Existing installs use their
// forward migration chain and this explicit ownership/policy binding projection.
const tables = objects.flatMap((sql) => {
  const match = sql.match(/^CREATE TABLE (?:IF NOT EXISTS )?(offline\.\w+)/u);
  return match ? [match[1]] : [];
});
const functions = objects.flatMap((sql) => {
  const match = sql.match(/^CREATE (?:OR REPLACE )?FUNCTION (offline\.\w+)\(\)/u);
  return match ? [match[1]] : [];
});
bindings.unshift(
  ...tables.map((table) => `ALTER TABLE ${table} OWNER TO stynx_owner;`),
  ...functions.map((fn) => `ALTER FUNCTION ${fn}() OWNER TO stynx_owner;`),
);
// The renderer binds identifier tokens only. Future migration grammar must be
// reviewed here rather than silently introducing string-literal substitution
// or a policy whose role list could disappear when the optional reader is off.
for (const sql of [...objects, ...bindings]) {
  if (/'(?:stynx_owner|stynx_app|stynx_reader)'/u.test(sql))
    throw new Error('Unsupported quoted offline role token');
  if (/^CREATE POLICY /u.test(sql)) {
    const clause = sql.match(/\bTO ([\s\S]*?) (?:USING|WITH CHECK)/u)?.[1];
    const roles = clause?.split(',').map((role) => role.trim());
    if (
      !roles?.includes('stynx_app') ||
      roles.some((role) => !['stynx_app', 'stynx_reader'].includes(role))
    )
      throw new Error('Unsupported offline policy role binding');
  }
}
const metadata = JSON.parse(
  readFileSync(resolve(root, 'packages/offline-sync/package.json'), 'utf8'),
);
for (const path of ['scripts/offline-storage-generate.mjs', 'tools/migration-linter/src/sql.ts']) {
  sources.push({
    path,
    sha256: createHash('sha256')
      .update(readFileSync(resolve(root, path)))
      .digest('hex'),
  });
}
const body = await format(
  `// Generated by scripts/offline-storage-generate.mjs; do not edit.\nexport const OFFLINE_STORAGE_TEMPLATE = ${JSON.stringify({ contractVersion: '1.0.0', packageVersion: metadata.version, sources, objects, bindings }, null, 2)} as const;\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
const target = resolve(root, 'packages/offline-sync/src/storage-template.generated.ts');
if (
  process.argv.slice(2).some((arg) => !['--check', '--write'].includes(arg)) ||
  process.argv.slice(2).length !== 1
)
  throw new Error('Use exactly --check or --write');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== body) throw new Error('Offline storage generation drift');
} else {
  const temporary = `${target}.${process.pid}.tmp`;
  writeFileSync(temporary, body);
  renameSync(temporary, target);
}
