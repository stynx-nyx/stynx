#!/usr/bin/env node
// Offline generation only: no consumer database connection and no policy repair.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitStatements } from '../tools/migration-linter/src/sql.ts';
import { format } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const files = [
  '0018_outbox.sql',
  '0021_outbox_event_log.sql',
  '0022_outbox_request_path.sql',
  '0025_outbox_attempt_guard_role_independent.sql',
  '0026_outbox_event_retirement.sql',
];
const objects = [];
const bindings = [];
const sources = [];
const migrationDir = resolve(root, 'packages/data/migrations/platform');
for (const file of readdirSync(migrationDir).filter((name) => name.endsWith('.sql'))) {
  if (
    !files.includes(file) &&
    /\boutbox\./u.test(readFileSync(resolve(migrationDir, file), 'utf8'))
  ) {
    throw new Error(`Unregistered outbox migration: ${file}`);
  }
}
for (const file of files) {
  const text = readFileSync(resolve(root, 'packages/data/migrations/platform', file), 'utf8');
  sources.push({
    path: `packages/data/migrations/platform/${file}`,
    sha256: createHash('sha256').update(text).digest('hex'),
  });
  for (const statement of splitStatements(text)) {
    const sql = statement.text.replace(/^\s*--[^\n]*(?:\n|$)/gmu, '').trim();
    if (sql.length === 0) continue;
    // 0021 shares a file with audit changes. Only explicitly outbox-owned
    // top-level statements are admitted; references inside function bodies
    // cannot turn an audit statement into an outbox declaration.
    if (
      !/^(?:CREATE (?:OR REPLACE )?(?:SCHEMA|SEQUENCE|TABLE|INDEX|FUNCTION|TRIGGER)|ALTER TABLE|INSERT INTO|GRANT|REVOKE|ALTER DEFAULT PRIVILEGES|CREATE POLICY|DROP POLICY|DO\s*\$\$)/u.test(
        sql,
      )
    )
      if (file !== '0021_outbox_event_log.sql')
        throw new Error(`Unsupported outbox statement in ${file}`);
      else continue;
    if (
      file === '0021_outbox_event_log.sql' &&
      !/^(?:CREATE (?:OR REPLACE )?(?:SEQUENCE|TABLE|FUNCTION) outbox\.|CREATE INDEX \w+ ON outbox\.|CREATE TRIGGER \w+ .*?ON outbox\.|ALTER TABLE outbox\.|INSERT INTO outbox\.|CREATE POLICY \w+ ON outbox\.|(?:GRANT|REVOKE)[\s\S]*? ON (?:SEQUENCE )?outbox\.)/u.test(
        sql,
      )
    ) {
      if (/\boutbox\./u.test(sql)) throw new Error(`Unsupported mixed outbox statement in ${file}`);
      continue;
    }
    if (/^(?:GRANT|REVOKE|ALTER DEFAULT PRIVILEGES|CREATE POLICY|DROP POLICY)/u.test(sql)) {
      bindings.push(sql);
      continue;
    }
    let portable = sql
      .replace(/CREATE TABLE (?!IF NOT EXISTS)/gu, 'CREATE TABLE IF NOT EXISTS ')
      .replace(/CREATE SEQUENCE (?!IF NOT EXISTS)/gu, 'CREATE SEQUENCE IF NOT EXISTS ')
      .replace(/CREATE INDEX (?!IF NOT EXISTS)/gu, 'CREATE INDEX IF NOT EXISTS ')
      .replace(/CREATE FUNCTION /gu, 'CREATE OR REPLACE FUNCTION ')
      .replace(/ADD COLUMN (?!IF NOT EXISTS)/gu, 'ADD COLUMN IF NOT EXISTS ')
      .replace(/DROP CONSTRAINT (?!IF EXISTS)/gu, 'DROP CONSTRAINT IF EXISTS ');
    if (/^INSERT INTO outbox\.legacy_ownership/u.test(portable))
      portable = portable.replace(/;$/u, ' ON CONFLICT (id) DO NOTHING;');
    const trigger = portable.match(/^CREATE TRIGGER (\w+)[\s\S]*? ON (outbox\.\w+)/u);
    if (trigger) portable = `DROP TRIGGER IF EXISTS ${trigger[1]} ON ${trigger[2]};\n${portable}`;
    objects.push(portable);
  }
}
const metadata = JSON.parse(readFileSync(resolve(root, 'packages/outbox/package.json'), 'utf8'));
for (const path of ['scripts/outbox-storage-generate.mjs', 'tools/migration-linter/src/sql.ts']) {
  sources.push({
    path,
    sha256: createHash('sha256')
      .update(readFileSync(resolve(root, path)))
      .digest('hex'),
  });
}
const body = await format(
  `// Generated by scripts/outbox-storage-generate.mjs; do not edit.\nexport const OUTBOX_STORAGE_TEMPLATE = ${JSON.stringify({ contractVersion: '1.0.0', packageVersion: metadata.version, sources, objects, bindings }, null, 2)} as const;\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
const target = resolve(root, 'packages/outbox/src/storage-template.generated.ts');
if (
  process.argv.slice(2).some((arg) => !['--check', '--write'].includes(arg)) ||
  process.argv.slice(2).length !== 1
)
  throw new Error('Use exactly --check or --write');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== body) throw new Error('Outbox storage generation drift');
} else {
  const temporary = `${target}.${process.pid}.tmp`;
  writeFileSync(temporary, body);
  renameSync(temporary, target);
}
